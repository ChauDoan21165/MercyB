// Thai B2–C1 opinion & argument frame bank for Vietnamese-speaking and
// English-speaking learners. Self-contained: inline types, exported array, no
// shared ./lessons dependency.
//
// Each entry is a reusable FRAME (a sentence opener / connector) tagged by the
// discourse function it performs: stating an opinion, agreeing, disagreeing
// softly, giving a reason, conceding, citing evidence, giving an example, and
// concluding. Every frame carries Thai script, romanization (where it helps),
// Vietnamese + English glosses, a usage note, and a FORMAL/CASUAL caution —
// Thai argument register shifts sharply between a meeting and a chat.
//
// "…" marks a slot where the learner inserts their own content.
//
// Romanization tone letters: (M)/(L)/(F)/(H)/(R); "ph/th/kh" aspirated;
// "dt/bp" unaspirated ต/ป.
//
// Native review: DEFERRED. Hand-derived for pedagogy; not validated by a
// native Thai reviewer.

