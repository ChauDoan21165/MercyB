// src/languages/thai/writing.ts
//
// Thai writing-practice bank for Vietnamese-speaking and English-speaking
// learners (CEFR A1–C2). Self-contained, like lessons-b2-core.ts: the Thai
// vertical has no shared ./lessons registry yet, so this module declares its
// own types inline and exports the task array.
//
// Each task gives a PROMPT (the thing to write), a MODEL ANSWER in Thai (with
// romanization at lower levels), Vietnamese + English glosses of the model,
// RUBRIC hints (what a good answer shows), and COMMON MISTAKES a Vietnamese
// learner makes. Forms covered: form-filling, messages, complaint, apology,
// work note, opinion paragraph, and essay/report frames.
//
// Romanization: tone letters where helpful — (M)=mid, (L)=low, (F)=falling,
// (H)=high, (R)=rising; "ph/th/kh" aspirated; "dt/bp" unaspirated ต/ป. Lower
// levels (A1–B1) always carry romanization; B2–C2 model answers may omit it.
//
// Native review: DEFERRED. Advanced model answers are hand-derived for
// pedagogy and have NOT been validated by a native Thai reviewer.

