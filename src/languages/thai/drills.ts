// src/languages/thai/drills.ts
//
// Thai practice drills for Vietnamese-speaking and English-speaking learners.
//
// Self-contained: declares its own types inline and exports the drill array.
// Two drill families, both NON-AUDIO and with NO scoring engine — this is
// pure DATA an app layer renders and grades:
//
//   • classifier   — Thai "ลักษณนาม" (measure-word) practice. The hard part
//                     for VN/EN learners: the right classifier depends on the
//                     noun, and the pattern is noun + number + classifier.
//   • tone_awareness— text-only tone reasoning: minimal pairs/triples that
//                     differ ONLY by tone, and tone-name identification. No
//                     audio is implied; learners reason from script + the
//                     romanized tone marks. Vietnamese speakers already have
//                     a tone instinct — these drills transfer it to Thai.
//
// Vietnamese-first: every drill carries `explanation_vi` + `explanation_en`.
// Native-speaker review is DEFERRED — this set does NOT claim native review.

