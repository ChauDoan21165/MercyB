// src/languages/thai/sentencePatterns.ts
//
// Thai sentence-pattern bank for Vietnamese-speaking and English-speaking
// learners.
//
// Self-contained PURE DATA: declares its own types inline and exports the
// pattern array. No audio, no scoring engine — an app layer renders these as
// "fill-the-slot" sentence frames. Each pattern carries:
//   • pattern_th  — the frame, with `___` marking substitution slots
//   • romanization
//   • meaning_vi / meaning_en
//   • explanation_vi / explanation_en  (how/when to use it)
//   • slots        — what can fill each `___`, with VN + EN glosses
//   • examples     — concrete filled sentences (Thai + romanization + VN + EN)
//   • common_mistake — the typical VN/EN learner error + the fix
//
// Coverage: A1–B2 primarily, plus some C1/C2 formal/discourse frames.
// Vietnamese-first throughout. Native-speaker review is DEFERRED — this bank
// does NOT claim native review.

export type ThaiCefrLevel = "A1" | "A2" | "B1" | "B2" | "C1" | "C2";

export type ThaiPatternTopic =
  | "greeting"
  | "want_need"
  | "can_cannot"
  | "location"
  | "time"
  | "buying"
  | "asking"
  | "giving_reason"
  | "comparing"
  | "polite_request"
  | "complaint"
  | "opinion";

export type ThaiPatternSlot = {
  /** Slot label as it appears conceptually in the frame (e.g. "VERB", "NOUN"). */
  name: string;
  /** A few Thai fillers that fit the slot. */
  fills_th: string[];
  gloss_vi: string;
  gloss_en: string;
};

export type ThaiPatternExample = {
  th: string;
  rtgs: string;
  vi: string;
  en: string;
};

export type ThaiCommonMistake = {
  /** The wrong form learners produce. */
  wrong: string;
  fix_vi: string;
  fix_en: string;
};

export type ThaiSentencePattern = {
  id: string;
  level: ThaiCefrLevel;
  topic: ThaiPatternTopic;
  /** The frame; `___` marks each substitution slot. */
  pattern_th: string;
  romanization: string;
  meaning_vi: string;
  meaning_en: string;
  explanation_vi: string;
  explanation_en: string;
  slots: ThaiPatternSlot[];
  examples: ThaiPatternExample[];
  common_mistake: ThaiCommonMistake;
};

