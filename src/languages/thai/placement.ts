// ── Level mapping ──────────────────────────────────────────────────────────
// Recommend the HIGHEST level at which the learner scored at or above
// `passRatio` (default 0.6), provided every lower level also cleared the bar.
// Floor is "A1". Input is the ratio (0..1) of correct answers per level.
export function recommendLevel(
  correctRatioByLevel: Partial<Record<ThaiCefrLevel, number>>,
  passRatio = 0.6,
): ThaiCefrLevel {
  let result: ThaiCefrLevel = "A1";
  for (const level of LEVEL_ORDER) {
    const ratio = correctRatioByLevel[level] ?? 0;
    if (ratio >= passRatio) {
      result = level;
    } else {
      break;
    }
  }
  return result;
}

