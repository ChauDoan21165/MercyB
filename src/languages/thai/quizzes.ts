// src/languages/thai/quizzes.ts
//
// Thai quiz bank for Vietnamese-speaking and English-speaking learners.
//
// Self-contained: declares its own types inline and exports the quiz array.
// No audio, no scoring engine — this is pure question DATA that an app layer
// renders and grades. Vietnamese-first: every item carries a Vietnamese
// explanation (`explanation_vi`) alongside an English one (`explanation_en`).
// Thai script is the source of truth; `romanization` is a practical reading
// aid (loose RTGS with tone marks where useful).
//
// Coverage spans A1–C2, weighted toward A1–B2 (the survival + working band).
// Native-speaker review is DEFERRED — this bank does NOT claim native review.

export type ThaiCefrLevel = "A1" | "A2" | "B1" | "B2" | "C1" | "C2";

export type ThaiQuizType =
  | "multiple_choice"
  | "fill_blank"
  | "reorder"
  | "match_meaning"
  | "polite_form";

export type ThaiQuizItem = {
  id: string;
  level: ThaiCefrLevel;
  type: ThaiQuizType;
  /** Vietnamese instruction / question stem. */
  prompt_vi: string;
  /** English instruction / question stem. */
  prompt_en: string;
  /** Thai text the item operates on (sentence, word, or blank line). */
  prompt_th?: string;
  /** Romanization of prompt_th / answer, where it helps the learner. */
  romanization?: string;
  /** Choices for multiple_choice / match_meaning. */
  options?: string[];
  /** Scrambled tokens for `reorder` items. */
  tokens?: string[];
  /** Correct answer (full Thai string, or the chosen option). */
  answer: string;
  /** Vietnamese answer explanation. */
  explanation_vi: string;
  /** English answer explanation. */
  explanation_en: string;
};

