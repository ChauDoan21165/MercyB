// src/languages/thai/mistakeRepairDrills.ts
//
// Thai mistake-repair drills for Vietnamese- and English-speaking learners.
// Each drill takes a realistic WRONG input, shows the CORRECTED form (Thai
// script + romanization), explains why it's wrong (Vietnamese + English),
// gives a repair strategy, and ends with a short practice item the learner
// redoes to lock in the fix.
//
// Topics: particles, pronouns, word order, classifiers, register, negation,
// tense markers, over-literal Vietnamese translation, over-literal English
// translation, tone-awareness warnings.
//
// Romanization tone diacritics:
//   mid = plain (a) · low = à · falling = â · high = á · rising = ǎ
//   long vowels are doubled (aa).
//
// NATIVE REVIEW DEFERRED — teaching draft, not a vetted authority.

export type ThaiRepairTopic =
  | "particles"
  | "pronouns"
  | "word-order"
  | "classifiers"
  | "register"
  | "negation"
  | "tense-markers"
  | "over-literal-vi"
  | "over-literal-en"
  | "tone-awareness";

export type ThaiRepairAudience = "vi" | "en" | "both";

export interface ThaiRepairDrill {
  /** Stable kebab-case id, unique across the bank. */
  id: string;
  topic: ThaiRepairTopic;
  /** L1 group most at risk. */
  audience: ThaiRepairAudience;
  /** The wrong input (Thai, or mixed) the learner produced. */
  wrong: string;
  /** Romanization of the wrong form. */
  wrongRoman?: string;
  /** The corrected Thai form. */
  corrected: string;
  /** Romanization of the corrected form. */
  correctedRoman?: string;
  /** English gloss of the intended meaning. */
  gloss_en: string;
  /** Why the wrong form is wrong — Vietnamese. */
  whyWrong_vi: string;
  /** Why the wrong form is wrong — English. */
  whyWrong_en: string;
  /** A short, actionable repair strategy. */
  repairStrategy: string;
  /** A practice item to redo and cement the fix. */
  practice: string;
}

