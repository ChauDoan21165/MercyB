// src/languages/thai/scenarios.ts
//
// Thai practical scenario packs for Vietnamese + English learners.
// Each pack is a small, app-ready unit: a situation, a learner goal, useful
// phrases, a model response, an escalation phrase (for when things go wrong),
// and a cultural / register note.
//
// Self-contained: types defined inline (the thai/ package has no shared
// scenarios module yet). Swap to type-only imports when one exists.
//
// Conventions
//   - Thai script primary; `rtgs` light Royal-Thai-style romanization on every
//     Thai utterance (phrases, model response, escalation).
//   - vi = Vietnamese guidance, en = English guidance. Both always present.
//   - Register notes flag politeness particles (ครับ/ค่ะ), formality, and
//     face-saving norms that matter in real Thai interactions.
//
// NOTE: not natively reviewed yet (native review deferred).

