function normalizeKidPage25Key(value?: string | null): string {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

export function getKidPage25Item(
  key?: string | null,
): KidPage25Item | null {
  const normalized = normalizeKidPage25Key(key);
  if (!normalized) return null;

  return (
    KID_PAGE_25_ITEMS.find(
      (item) => normalizeKidPage25Key(item.key) === normalized,
    ) ?? null
  );
}