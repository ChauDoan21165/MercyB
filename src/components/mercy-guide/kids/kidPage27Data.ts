function normalizeKidPage27Key(value?: string | null): string {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

export function getKidPage27Item(
  key?: string | null,
): KidPage27Item | null {
  const normalized = normalizeKidPage27Key(key);
  if (!normalized) return null;

  return (
    KID_PAGE_27_ITEMS.find(
      (item) => normalizeKidPage27Key(item.key) === normalized,
    ) ?? null
  );
}