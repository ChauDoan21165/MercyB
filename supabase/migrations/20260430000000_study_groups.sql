-- Step 6 (Community) — Study groups MVP.
--
-- Greenfield: no groups concept existed before. This migration is the
-- foundation; group chat / messaging is intentionally out of scope and
-- will land in a follow-up PR.
--
-- Design:
--   - Two tables: study_groups (one per group) and study_group_members
--     (one per (group, user) pair).
--   - Public groups are visible to any signed-in user; private groups are
--     visible only to their members. Joining a private group requires
--     matching the invite_code, validated inside the join_study_group
--     SECURITY DEFINER RPC so RLS can't be bypassed by direct INSERT.
--   - member_count on study_groups is a denormalized counter maintained by
--     a trigger on study_group_members. It's not the source of truth — it's
--     for cheap UI rendering. Source of truth is COUNT(*) of members.
--   - On group create, an AFTER INSERT trigger seeds the owner's membership
--     row with role='owner'. This keeps the owner addressable in the
--     members list without a special case in the client.
--   - invite_code is auto-generated by a BEFORE INSERT trigger when
--     is_private = true and no code was provided. 8-char base32-ish.
--
-- RLS summary:
--   study_groups
--     SELECT: public OR caller is a member
--     INSERT: caller must be the owner_user_id
--     UPDATE / DELETE: owner only
--   study_group_members
--     SELECT: visible to other members of the same group, plus visible
--             on public groups (so non-members can preview member count)
--     INSERT: no client-facing policy. Inserts go through:
--             - the seed_owner_membership trigger on group create, OR
--             - the join_study_group RPC (SECURITY DEFINER bypasses RLS)
--     DELETE: own row (leave) OR group owner (kick); kick is normally
--             routed through the kick_study_group_member RPC for clarity.
--
-- Reversibility:
--   DROP FUNCTION IF EXISTS public.kick_study_group_member(uuid, uuid);
--   DROP FUNCTION IF EXISTS public.join_study_group(uuid, text);
--   DROP TRIGGER IF EXISTS trg_study_group_members_count ON public.study_group_members;
--   DROP FUNCTION IF EXISTS public.refresh_study_group_member_count();
--   DROP TRIGGER IF EXISTS trg_study_groups_seed_owner_membership ON public.study_groups;
--   DROP FUNCTION IF EXISTS public.study_groups_seed_owner_membership();
--   DROP TRIGGER IF EXISTS trg_study_groups_set_invite_code ON public.study_groups;
--   DROP FUNCTION IF EXISTS public.study_groups_set_invite_code();
--   DROP TABLE IF EXISTS public.study_group_members;
--   DROP TABLE IF EXISTS public.study_groups;

-- ── 1. Tables ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.study_groups (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name          text NOT NULL,
  description   text,
  owner_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  is_private    boolean NOT NULL DEFAULT false,
  invite_code   text UNIQUE,
  created_at    timestamptz NOT NULL DEFAULT now(),
  member_count  integer NOT NULL DEFAULT 0,
  CONSTRAINT study_groups_name_chk
    CHECK (length(trim(name)) BETWEEN 2 AND 80),
  CONSTRAINT study_groups_member_count_nonneg
    CHECK (member_count >= 0)
);

CREATE INDEX IF NOT EXISTS idx_study_groups_owner
  ON public.study_groups (owner_user_id);

-- Public-discovery feed: most recently created public groups first.
CREATE INDEX IF NOT EXISTS idx_study_groups_public_recent
  ON public.study_groups (created_at DESC)
  WHERE is_private = false;

CREATE TABLE IF NOT EXISTS public.study_group_members (
  group_id  uuid NOT NULL REFERENCES public.study_groups(id) ON DELETE CASCADE,
  user_id   uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  joined_at timestamptz NOT NULL DEFAULT now(),
  role      text NOT NULL DEFAULT 'member',
  PRIMARY KEY (group_id, user_id),
  CONSTRAINT study_group_members_role_chk
    CHECK (role IN ('owner', 'admin', 'member'))
);

-- "Which groups am I in?" lookup — covers getMyGroups in studyGroupClient.
CREATE INDEX IF NOT EXISTS idx_study_group_members_user
  ON public.study_group_members (user_id);

COMMENT ON TABLE public.study_groups IS
  'User-formed study groups (Step 6 / Community). MVP: no group chat, just join/leave/list.';

COMMENT ON TABLE public.study_group_members IS
  'Membership rows. INSERT only via join_study_group RPC or the owner-seed trigger; DELETE permitted for own row (leave) or by owner (kick).';

-- ── 2. invite_code auto-gen for private groups ───────────────────────────

CREATE OR REPLACE FUNCTION public.study_groups_set_invite_code()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.is_private AND NEW.invite_code IS NULL THEN
    -- 8 hex chars uppercased — short enough to share, long enough to avoid
    -- accidental collisions across the active set. UNIQUE constraint on
    -- invite_code will reject the rare conflict and the client will retry.
    NEW.invite_code := upper(substring(replace(gen_random_uuid()::text, '-', ''), 1, 8));
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_study_groups_set_invite_code ON public.study_groups;
CREATE TRIGGER trg_study_groups_set_invite_code
  BEFORE INSERT ON public.study_groups
  FOR EACH ROW
  EXECUTE FUNCTION public.study_groups_set_invite_code();

-- ── 3. Owner becomes first member on group create ────────────────────────

CREATE OR REPLACE FUNCTION public.study_groups_seed_owner_membership()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.study_group_members (group_id, user_id, role)
    VALUES (NEW.id, NEW.owner_user_id, 'owner')
    ON CONFLICT (group_id, user_id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_study_groups_seed_owner_membership ON public.study_groups;
CREATE TRIGGER trg_study_groups_seed_owner_membership
  AFTER INSERT ON public.study_groups
  FOR EACH ROW
  EXECUTE FUNCTION public.study_groups_seed_owner_membership();

-- ── 4. member_count maintenance ──────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.refresh_study_group_member_count()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    UPDATE public.study_groups
       SET member_count = member_count + 1
     WHERE id = NEW.group_id;
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    -- GREATEST guard prevents the counter going negative if the trigger
    -- ever fires twice for one logical removal (defensive — should not
    -- happen given AFTER DELETE FOR EACH ROW semantics).
    UPDATE public.study_groups
       SET member_count = GREATEST(member_count - 1, 0)
     WHERE id = OLD.group_id;
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_study_group_members_count ON public.study_group_members;
CREATE TRIGGER trg_study_group_members_count
  AFTER INSERT OR DELETE ON public.study_group_members
  FOR EACH ROW
  EXECUTE FUNCTION public.refresh_study_group_member_count();

-- ── 5. RLS ───────────────────────────────────────────────────────────────

ALTER TABLE public.study_groups        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_group_members ENABLE ROW LEVEL SECURITY;

-- study_groups: see public groups, or any group you're a member of.
DROP POLICY IF EXISTS study_groups_select ON public.study_groups;
CREATE POLICY study_groups_select
  ON public.study_groups
  FOR SELECT
  TO authenticated
  USING (
    is_private = false
    OR EXISTS (
      SELECT 1 FROM public.study_group_members m
       WHERE m.group_id = study_groups.id
         AND m.user_id  = auth.uid()
    )
  );

-- study_groups: any authenticated user can create a group, becoming owner.
DROP POLICY IF EXISTS study_groups_insert_owner ON public.study_groups;
CREATE POLICY study_groups_insert_owner
  ON public.study_groups
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = owner_user_id);

DROP POLICY IF EXISTS study_groups_update_owner ON public.study_groups;
CREATE POLICY study_groups_update_owner
  ON public.study_groups
  FOR UPDATE
  TO authenticated
  USING      (auth.uid() = owner_user_id)
  WITH CHECK (auth.uid() = owner_user_id);

DROP POLICY IF EXISTS study_groups_delete_owner ON public.study_groups;
CREATE POLICY study_groups_delete_owner
  ON public.study_groups
  FOR DELETE
  TO authenticated
  USING (auth.uid() = owner_user_id);

-- study_group_members: visible if you're a member, or for any public group.
-- This makes the public group cards show member count + roster honestly.
DROP POLICY IF EXISTS study_group_members_select ON public.study_group_members;
CREATE POLICY study_group_members_select
  ON public.study_group_members
  FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.study_group_members me
       WHERE me.group_id = study_group_members.group_id
         AND me.user_id  = auth.uid()
    )
    OR EXISTS (
      SELECT 1 FROM public.study_groups g
       WHERE g.id = study_group_members.group_id
         AND g.is_private = false
    )
  );

-- INSERT into study_group_members has no client-facing policy — all writes
-- go through:
--   * trg_study_groups_seed_owner_membership (SECURITY DEFINER, on create)
--   * join_study_group RPC (SECURITY DEFINER, on join)
-- This keeps invite-code validation un-bypassable.

DROP POLICY IF EXISTS study_group_members_delete_self_or_owner ON public.study_group_members;
CREATE POLICY study_group_members_delete_self_or_owner
  ON public.study_group_members
  FOR DELETE
  TO authenticated
  USING (
    user_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM public.study_groups g
       WHERE g.id = study_group_members.group_id
         AND g.owner_user_id = auth.uid()
    )
  );

-- ── 6. RPC: join_study_group ─────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.join_study_group(
  p_group_id    uuid,
  p_invite_code text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user  uuid := auth.uid();
  v_group public.study_groups%ROWTYPE;
BEGIN
  IF v_user IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_signed_in');
  END IF;

  SELECT * INTO v_group FROM public.study_groups WHERE id = p_group_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'group_not_found');
  END IF;

  IF v_group.is_private THEN
    IF p_invite_code IS NULL OR p_invite_code <> v_group.invite_code THEN
      RETURN jsonb_build_object('ok', false, 'error', 'invalid_invite_code');
    END IF;
  END IF;

  -- Idempotent: re-joining is a no-op; never fails the call.
  INSERT INTO public.study_group_members (group_id, user_id, role)
       VALUES (p_group_id, v_user, 'member')
  ON CONFLICT (group_id, user_id) DO NOTHING;

  RETURN jsonb_build_object('ok', true, 'group_id', p_group_id);
END;
$$;

GRANT EXECUTE ON FUNCTION public.join_study_group(uuid, text) TO authenticated;

COMMENT ON FUNCTION public.join_study_group(uuid, text) IS
  'Join a study group. Public groups skip invite check; private require matching invite_code. Idempotent.';

-- ── 7. RPC: kick_study_group_member ──────────────────────────────────────

CREATE OR REPLACE FUNCTION public.kick_study_group_member(
  p_group_id uuid,
  p_user_id  uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller uuid := auth.uid();
  v_owner  uuid;
BEGIN
  IF v_caller IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_signed_in');
  END IF;

  SELECT owner_user_id INTO v_owner
    FROM public.study_groups
   WHERE id = p_group_id;

  IF v_owner IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'group_not_found');
  END IF;

  IF v_owner <> v_caller THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_owner');
  END IF;

  IF v_owner = p_user_id THEN
    -- Owner cannot kick themselves; they must delete the group instead.
    RETURN jsonb_build_object('ok', false, 'error', 'cannot_kick_owner');
  END IF;

  DELETE FROM public.study_group_members
   WHERE group_id = p_group_id AND user_id = p_user_id;

  RETURN jsonb_build_object('ok', true);
END;
$$;

GRANT EXECUTE ON FUNCTION public.kick_study_group_member(uuid, uuid) TO authenticated;

COMMENT ON FUNCTION public.kick_study_group_member(uuid, uuid) IS
  'Remove a member from a group. Caller must be the group owner; cannot kick the owner themselves.';
