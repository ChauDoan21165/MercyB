function normalizeKidPage26Key(value?: string | null): string {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

export function getKidPage26Item(
  key?: string | null,
): KidPage26Item | null {
  const normalized = normalizeKidPage26Key(key);
  if (!normalized) return null;

  return (
    KID_PAGE_26_ITEMS.find(
      (item) => normalizeKidPage26Key(item.key) === normalized,
    ) ?? null
  );
}