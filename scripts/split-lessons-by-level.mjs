// Splits each language's lessons.ts into per-level .ts files.
// Run via: node scripts/split-lessons-by-level.mjs
//
// Strategy:
//   1. Use tsx to dynamically import each language's `lessons` named export.
//   2. Group lessons by `.level`.
//   3. Emit `lessons-{level}.ts` for each level with the data inlined as
//      a JSON literal cast to the language's Lesson type.
//
// The original `lessons.ts` is left untouched here — it's edited
// separately in the same PR to (a) drop the giant `lessons` const and
// (b) add a small async registry that loads per-level chunks on demand.

import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
// tsx loader is wired in via NODE_OPTIONS="--import tsx" by the runner.

const REPO_ROOT = resolve(__dirname, "..");

const LANGUAGES = [
  { code: "chinese", typeName: "ChineseLesson" },
  { code: "japanese", typeName: "JapaneseLesson" },
  { code: "korean", typeName: "KoreanLesson" },
  { code: "french", typeName: "FrenchLesson" },
  { code: "german", typeName: "GermanLesson" },
];

const LEVELS = ["A1", "A2", "B1", "B2", "C1", "C2"];

for (const lang of LANGUAGES) {
  const modPath = resolve(
    REPO_ROOT,
    `src/languages/${lang.code}/lessons.ts`,
  );
  const mod = await import(modPath);
  const lessons = mod.lessons;
  if (!Array.isArray(lessons)) {
    throw new Error(`No lessons array in ${modPath}`);
  }

  const counts = {};
  for (const level of LEVELS) {
    const subset = lessons.filter((l) => l.level === level);
    counts[level] = subset.length;

    const outPath = resolve(
      REPO_ROOT,
      `src/languages/${lang.code}/lessons-${level.toLowerCase()}.ts`,
    );

    const body = `// Auto-generated by scripts/split-lessons-by-level.mjs.
// Edit the source lesson content here directly. DO NOT regenerate
// from a stale lessons.ts — the registry replaced that file.

import type { ${lang.typeName} } from "./lessons";

export const lessons: ${lang.typeName}[] = ${JSON.stringify(subset, null, 2)};

export default lessons;
`;

    writeFileSync(outPath, body, "utf8");
  }

  console.log(
    `${lang.code}: total=${lessons.length} ` +
      LEVELS.map((l) => `${l}=${counts[l]}`).join(" "),
  );
}

console.log("Done.");
